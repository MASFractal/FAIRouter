from __future__ import annotations

import numpy as np

from fai_router.enums import Style


class Settings:
    """Общие настройки роутера. Значения статические, как и в версии на C#."""

    # Доли важности качества, времени и цены в метрике R = WQ*q - WC*c - WT*t.
    # Каждое слагаемое приводится к одному масштабу внутри группы кандидатов, поэтому веса
    # сравнивают сравнимое: половина решения за качеством, по четверти за ценой и временем.
    WQ: float = 0.5
    WT: float = 0.25
    WC: float = 0.25

    # Множитель температуры выбора, обозначенный в описании как C. Ноль делает выбор жадным.
    #
    # Температура считается по отзывам из отрезка от нуля до единицы, а сравнивается с
    # метрикой R. Раньше R не был приведен к единому масштабу, и множитель приходилось
    # подбирать заново при любом заметном изменении весов WQ/WC/WT. Теперь env.get_top_k
    # делит R на длину вектора весов (WQ, WC, WT), поэтому масштаб R держится порядка
    # единицы независимо от того, как заданы веса: проверено на равномерном масштабировании
    # весов в 500 раз (результат сэмплирования совпал буквально до последней цифры) и на
    # смене профиля весов (только цена, только время, качество прежде всего), разброс R
    # внутри группы остался в пределах 0,6-1,0 вместо разницы в тысячи раз.
    #
    # Значение 30 подобрано заново под этот новый масштаб: на контрольном тесте с тремя
    # типами задач весь диапазон C от 10 до 50 стабильно дает 18-20 удачных запусков из 20
    # (раньше при C=1 было только 4 из 20).
    temperature_scale: float = 30.0

    # Дисперсия, приписываемая кандидату, о котором нечего знать: наибольшая для отрезка 0..1,
    # поэтому новичок получает самую высокую температуру и участвует в выборе чаще
    UNKNOWN_VARIANCE: float = 0.25

    # Среднее по векторам задач. Вычитается из признаков перед прогнозом и перед обучением.
    # Задается один раз по накопленным ходам и дальше не меняется: веса обучены в пространстве
    # с этим средним, и подмена среднего обесценивает их. None отключает вычитание.
    task_mean: np.ndarray | None = None

    # Клиент модели для распознавания задачи и разбора ответа
    llm = None

    # Число объемных признаков запроса: длина входа и ожидаемая длина ответа
    FEATURES_DIM: int = 2

    # Числовые метрики спецификации кроме кода стиля: symbol_length, word_length,
    # paragraph_count, section_count, list_item_count, table_count, code_block_count,
    # formula_count, heading_depth, avg_sentence_length, readability, term_density, formality
    SPEC_NUMERIC_FEATURES: int = 13

    @classmethod
    def features_spec_dim(cls) -> int:
        """Размерность вектора спецификации. Вычисляется из перечисления стилей и числа
        метрик, а не задается константой, чтобы не расходиться с вектором при добавлении полей.

        Проверялось добавление кросс-признаков «стиль x объем», чтобы один вектор кандидата
        мог выучить разный наклон по объему для каждого стиля: 10 стилей * 2 объемных
        координаты, размерность 43 вместо 23. Идея не подтвердилась измерением, см.
        docs/research/exploration.md, «интерактивные признаки»."""
        return len(Style) + cls.SPEC_NUMERIC_FEATURES

    @classmethod
    def full_dim(cls) -> int:
        return cls.FEATURES_DIM + cls.features_spec_dim()

    @classmethod
    def center(cls, features: np.ndarray) -> np.ndarray:
        """Приводит признаки задачи к виду, в котором работают прогноз и обучение: вычитает
        среднее и возвращает длину к единице.

        Возврат длины обязателен. Шаг обучения меняет оценку пропорционально квадрату длины
        вектора задачи, а после вычитания среднего вектор укорачивается в разы, и обучение
        замедляется во столько же. На трех типах задач один возврат длины поднял долю удачных
        запусков с 4 из 20 до 18 из 20."""
        if cls.task_mean is None:
            return features
        centered = features - cls.task_mean
        norm = np.linalg.norm(centered)
        return centered if norm < 1e-12 else centered / norm

    @classmethod
    def require_llm(cls):
        if cls.llm is None:
            raise RuntimeError(
                "Settings.llm не задан: назначьте клиент модели до обращения к сервисам распознавания.")
        return cls.llm
