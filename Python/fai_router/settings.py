from __future__ import annotations

from dataclasses import dataclass
from typing import TYPE_CHECKING

import numpy as np

from fai_router.enums import Domain, ProgrammingLanguage, ScienceField, Style, TaskKind

if TYPE_CHECKING:
    from fai_router.training.calibration import Calibration


@dataclass(frozen=True)
class RouteWeights:
    """Веса метрики R и множитель температуры, действующие на один выбор.

    Отдельный тип нужен потому, что веса задает заказчик выбора, а не процесс. Хост может вести
    несколько выборов одновременно и с разными предпочтениями: одному важна цена, другому
    качество. Пока значения жили только в статических полях Settings, соседний выбор менял
    условия уже начатому, и промах нечем было воспроизвести."""

    WQ: float
    WC: float
    WT: float
    # Множитель температуры выбора; ноль делает выбор жадным
    temperature_scale: float

    @classmethod
    def quality(cls) -> "RouteWeights":
        """Профиль «качество прежде всего»: 0,8 / 0,10 / 0,10. По замеру router-eval обходит по
        качеству все стратегии, включая всегда самую дорогую модель."""
        return cls(0.8, 0.10, 0.10, Settings.temperature_scale)

    @classmethod
    def balance(cls) -> "RouteWeights":
        """Профиль «баланс»: 0,5 / 0,25 / 0,25, веса по умолчанию. Половина решения за качеством,
        по четверти за ценой и временем."""
        return cls(0.5, 0.25, 0.25, Settings.temperature_scale)

    @classmethod
    def price(cls) -> "RouteWeights":
        """Профиль «экономный»: 0,3 / 0,60 / 0,10. По замеру router-eval дает качество выше, чем
        всегда самая дешевая модель, почти по той же цене."""
        return cls(0.3, 0.60, 0.10, Settings.temperature_scale)

    @classmethod
    def profile(cls, name: "str | RouteWeights | None") -> "RouteWeights | None":
        """Веса по имени профиля: quality, balance или price. Готовые веса возвращаются как есть,
        None означает веса из Settings."""
        if name is None or isinstance(name, RouteWeights):
            return name
        key = name.strip().lower()
        if key == "quality":
            return cls.quality()
        if key in ("balance", "balanced"):
            return cls.balance()
        if key in ("price", "cheap", "economy"):
            return cls.price()
        raise ValueError(f"Неизвестный профиль весов «{name}»: есть quality, balance и price.")



@dataclass(frozen=True)
class SufficiencyBar:
    """Планка достаточности качества на один выбор: какой вероятности лайка должен достигать ответ.

    Линейная метрика R разменивает качество на цену без ограничений, а потеря от недостаточного
    ответа не линейна: человек уходит, и сэкономленное ничего не стоит. Планка меняет смысл выбора:
    сначала отсеять тех, кто прогнозируемо не дотягивает, а среди остальных не переплачивать."""

    # Какая вероятность лайка обязательна, от 0 до 1
    bar: float
    # Перевод прогноза качества в вероятность лайка
    calibration: "Calibration"
    # Доля лайков по всем ходам: к ней стягивается малоизученный кандидат
    prior_rate: float
    # Сколько оценок весит эта доля против собственного прогноза кандидата
    prior_strength: float = 5.0

    def sufficiency(self, experience: int, quality: float) -> float:
        """Вероятность, что кандидат с таким прогнозом устроит человека, с усадкой по его опыту.
        Новый кандидат получает долю лайков по всем ходам, а не свой прогноз: калибровка подобрана
        на тех, кто уже побеждал, и на незнакомом ее наклону верить рано."""
        n = max(experience, 0)
        return (n * self.calibration.predict(quality) + self.prior_strength * self.prior_rate) / (n + self.prior_strength)


class Settings:
    """Общие настройки роутера. Значения статические, как и в версии на C#."""

    # Доли важности качества, времени и цены в метрике R = WQ*q - WC*c - WT*t.
    # Каждое слагаемое приводится к одному масштабу внутри группы кандидатов, поэтому веса
    # сравнивают сравнимое: половина решения за качеством, по четверти за ценой и временем.
    WQ: float = 0.5
    WT: float = 0.25
    WC: float = 0.25

    # Множитель температуры выбора, обозначенный в описании как C. Ноль делает выбор жадным.
    #
    # Температура считается по отзывам из отрезка от нуля до единицы, а сравнивается с
    # метрикой R. Раньше R не был приведен к единому масштабу, и множитель приходилось
    # подбирать заново при любом заметном изменении весов WQ/WC/WT. Теперь env.get_top_k
    # делит R на длину вектора весов (WQ, WC, WT), поэтому масштаб R держится порядка
    # единицы независимо от того, как заданы веса: проверено на равномерном масштабировании
    # весов в 500 раз (результат сэмплирования совпал буквально до последней цифры) и на
    # смене профиля весов (только цена, только время, качество прежде всего), разброс R
    # внутри группы остался в пределах 0,6-1,0 вместо разницы в тысячи раз.
    #
    # Значение 30 подобрано под этот масштаб на старте со случайных весов: на контрольном тесте
    # с тремя типами задач доля удачных запусков из 100 равна 92 при C=50, 85 при C=30, 71 при
    # C=20 и 57 при C=10 (замер 05.10.2026). Без разведки роутер закрепляется на первом
    # одобренном кандидате, поэтому общий множитель ниже 30 не опускается.
    temperature_scale: float = 30.0

    # Множитель температуры для роутера, все кандидаты которого стартуют с начальных весов по
    # рейтингам (так собирают фабрики FaiRouter). Там долгая разведка только отнимает ходы. По
    # сквозной модели (три типа задач, 600 ходов, 150 прогонов, профиль quality) качество на
    # ходах 1-100 и 401-600: при точных начальных весах 0,818 и 0,859 при C=30, 0,865 и 0,878
    # при C=10, 0,879 и 0,886 при C=5; при грубых 0,816 и 0,864 при C=30, 0,854 и 0,868 при
    # C=10, 0,857 и 0,863 при C=5. Значение 10 лучшее при грубых весах и не хуже при точных
    PRIOR_TEMPERATURE_SCALE: float = 10.0

    # Доля содержания в итоговой оценке ответа; форма получает остальное. Для бизнес-задачи главное
    # это наполнение работы: таблица с выдуманными цифрами проходит сверку формы на отлично. Форма
    # не обнуляется: заказанный объем и структура тоже часть заказа
    content_weight: float = 0.7

    # Дисперсия, приписываемая кандидату, о котором нечего знать: наибольшая для отрезка 0..1,
    # поэтому новичок получает самую высокую температуру и участвует в выборе чаще
    UNKNOWN_VARIANCE: float = 0.25

    # Среднее по векторам задач. Вычитается из признаков перед прогнозом и перед обучением.
    # Задается один раз по накопленным ходам и дальше не меняется: веса обучены в пространстве
    # с этим средним, и подмена среднего обесценивает их. None отключает вычитание.
    task_mean: np.ndarray | None = None

    # Клиент модели для распознавания задачи и разбора ответа
    llm = None

    # Число признаков задачи вне спецификации: длина входа, ожидаемая длина ответа, длина
    # диалога, число ограничений, экспертность, трудность и опора на факты (InputFeatures)
    FEATURES_DIM: int = 7

    # Числовые метрики спецификации кроме кода стиля: symbol_length, word_length,
    # paragraph_count, section_count, list_item_count, table_count, code_block_count,
    # formula_count, heading_depth, avg_sentence_length, readability, term_density, formality
    SPEC_NUMERIC_FEATURES: int = 13

    @classmethod
    def current(cls) -> RouteWeights:
        """Нынешние веса одним значением: их получает выбор, который своих не назвал."""
        return RouteWeights(cls.WQ, cls.WC, cls.WT, cls.temperature_scale)

    @classmethod
    def features_spec_dim(cls) -> int:
        """Размерность вектора спецификации. Вычисляется из перечисления стилей и числа
        метрик, а не задается константой, чтобы не расходиться с вектором при добавлении полей.

        Проверялось добавление кросс-признаков «стиль x объем», чтобы один вектор кандидата
        мог выучить разный наклон по объему для каждого стиля: 10 стилей * 2 объемных
        координаты, размерность 43 вместо 23. Идея не подтвердилась измерением, см.
        docs/research/exploration.md, «интерактивные признаки»."""
        from fai_router.specifications import Specifications

        # У перечислений предмета первое значение означает «не задано» и разряда не имеет
        return (len(Style) + cls.SPEC_NUMERIC_FEATURES
                + (len(Domain) - 1) + (len(ProgrammingLanguage) - 1)
                + (len(ScienceField) - 1) + (len(TaskKind) - 1)
                + Specifications.language_dim() + 1)

    @classmethod
    def full_dim(cls) -> int:
        return cls.FEATURES_DIM + cls.features_spec_dim()

    @classmethod
    def center(cls, features: np.ndarray) -> np.ndarray:
        """Приводит признаки задачи к виду, в котором работают прогноз и обучение: вычитает
        среднее и возвращает длину к единице.

        Возврат длины обязателен. Шаг обучения меняет оценку пропорционально квадрату длины
        вектора задачи, а после вычитания среднего вектор укорачивается в разы, и обучение
        замедляется во столько же. На трех типах задач один возврат длины поднял долю удачных
        запусков с 4 из 20 до 18 из 20."""
        if cls.task_mean is None:
            return features
        centered = features - cls.task_mean
        norm = np.linalg.norm(centered)
        return centered if norm < 1e-12 else centered / norm

    @classmethod
    def require_llm(cls):
        if cls.llm is None:
            raise RuntimeError(
                "Settings.llm не задан: назначьте клиент модели до обращения к сервисам распознавания.")
        return cls.llm
