namespace FAI.Router.Enums;

/// <summary>
/// Причины недовольства ответом, которые человек назвал вместе с отзывом. Делятся на две оси, как и
/// оценка ответа судьей: содержание (ответ по существу) и форма (объем и стиль).
/// </summary>
/// <remarks>
/// Ось решает, чему учить. Причина по содержанию говорит о модели: она ответила не на то, ошиблась или
/// выдумала. Причина формы говорит о вкусе человека и о задании: тот же ответ другому человеку подошел
/// бы, и смена модели его вкус не исправит. Такой отзыв вектор качества не двигает, его учитывает
/// вызывающий как предпочтение человека.
/// </remarks>
[Flags]
public enum FeedbackReason
{
    /// <summary>Причина не названа</summary>
    None = 0,

    /// <summary>Ответ не на заданный вопрос</summary>
    OffTopic = 1,

    /// <summary>Ошибки и неточности</summary>
    Errors = 2,

    /// <summary>Выдуманные факты</summary>
    MadeUp = 4,

    /// <summary>Слишком длинно</summary>
    TooLong = 8,

    /// <summary>Слишком коротко</summary>
    TooShort = 16,

    /// <summary>Не тот стиль</summary>
    Style = 32,

    /// <summary>Причины по содержанию: вина модели</summary>
    Content = OffTopic | Errors | MadeUp,

    /// <summary>Причины формы: предпочтение человека</summary>
    Form = TooLong | TooShort | Style
}
